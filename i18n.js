(function () {
  const root  = document.documentElement;
  const nodes = Array.from(document.querySelectorAll('[data-i18n]'));
  const EN    = {};
  nodes.forEach(n => { EN[n.getAttribute('data-i18n')] = n.innerHTML; });

  const btnEn = document.getElementById('langEn');
  const btnAr = document.getElementById('langAr');

  function setLang(lang) {
    const ar = lang === 'ar';
    nodes.forEach(n => {
      const k = n.getAttribute('data-i18n');
      const v = ar ? AR[k] : EN[k];
      if (v !== undefined) n.innerHTML = v;
    });

    root.setAttribute('lang', ar ? 'ar' : 'en');
    root.setAttribute('dir',  ar ? 'rtl' : 'ltr');

    const m = META[ar ? 'ar' : 'en'];
    document.title = m.title;
    const desc = document.getElementById('metaDesc');
    if (desc) desc.setAttribute('content', m.desc);
    const set = (id, attr, val) => {
      const el = document.getElementById(id);
      if (el) el.setAttribute(attr, val);
    };
    set('slides',  'aria-label', m.slides);
    set('sPrev',   'aria-label', m.prev);
    set('sNext',   'aria-label', m.next);
    set('dots',    'aria-label', m.dots);
    set('lightbox','aria-label', m.lb);
    set('lbClose', 'aria-label', m.lbClose);

    if (btnEn && btnAr) {
      btnEn.classList.toggle('is-on', !ar);
      btnAr.classList.toggle('is-on', ar);
      btnEn.setAttribute('aria-pressed', String(!ar));
      btnAr.setAttribute('aria-pressed', String(ar));
    }

    try { localStorage.setItem('glove-lang', ar ? 'ar' : 'en'); } catch (e) {}
    window.dispatchEvent(new Event('langchange'));
  }

  if (btnEn) btnEn.addEventListener('click', () => setLang('en'));
  if (btnAr) btnAr.addEventListener('click', () => setLang('ar'));

  let saved = null;
  try { saved = localStorage.getItem('glove-lang'); } catch (e) {}
  if (!saved && (navigator.language || '').toLowerCase().startsWith('ar')) saved = 'ar';
  if (saved === 'ar') setLang('ar');
})();
